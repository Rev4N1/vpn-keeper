# build.ps1 - builds dist\vpn-keeper.exe with the C# compiler that ships with
# Windows (.NET Framework 4.8). No SDK, no NuGet. CI runs the same.
#
#   .\build.ps1          build
#   .\build.ps1 -Test    build, then run the tests (a fake window flashes briefly)
param([switch]$Test, [string]$Version)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { throw "C# compiler not found at $csc (.NET Framework 4.8 required)" }

if (-not $Version) {
    $ErrorActionPreference = 'Continue'
    $Version = (& git describe --tags --match 'v*' --always --dirty 2>$null)
    $ErrorActionPreference = 'Stop'
    if (-not $Version) { $Version = 'dev' }
}
$numeric = '0.0.0.0'
if ($Version -match '^v?(\d+)\.(\d+)\.(\d+)') { $numeric = "$($Matches[1]).$($Matches[2]).$($Matches[3]).0" }

New-Item -ItemType Directory -Force obj, dist | Out-Null
@"
// Generated by build.ps1 - do not edit.
using System.Reflection;
[assembly: AssemblyTitle("vpn-keeper")]
[assembly: AssemblyProduct("vpn-keeper")]
[assembly: AssemblyVersion("$numeric")]
[assembly: AssemblyFileVersion("$numeric")]
[assembly: AssemblyInformationalVersion("$Version")]
namespace VpnKeeper { static class BuildInfo { public const string Version = "$Version"; } }
"@ | Set-Content -Encoding UTF8 obj\BuildInfo.cs

function Compile([string]$out, [string]$target, [string[]]$sources, [string[]]$refs) {
    $a = @('/nologo', "/target:$target", '/optimize+', '/warnaserror+', '/nowarn:0649', '/platform:anycpu',
           '/codepage:65001', "/out:$out") + ($refs | ForEach-Object { "/r:$_" }) + $sources
    & $csc @a
    if ($LASTEXITCODE -ne 0) { throw "compile failed: $out" }
}

$build = (Resolve-Path obj\BuildInfo.cs).Path
$app = @(Get-ChildItem src\*.cs | ForEach-Object FullName)
Compile 'dist\vpn-keeper.exe' 'exe' ($app + $build) @('System.dll', 'System.Core.dll')
Write-Host "built dist\vpn-keeper.exe ($Version)"

if ($Test) {
    # The fake must be named SnwlConnect.exe: the agent looks for that process.
    Compile 'obj\SnwlConnect.exe' 'winexe' @((Resolve-Path tests\FakeClient.cs).Path, (Resolve-Path src\Totp.cs).Path) `
        @('System.dll', 'System.Drawing.dll', 'System.Windows.Forms.dll')
    # tests.exe = the suite + every src file except Program.cs (its Main would clash).
    $lib = $app | Where-Object { $_ -notmatch '\\Program\.cs$' }
    Compile 'obj\tests.exe' 'exe' (@((Resolve-Path tests\Tests.cs).Path) + $lib + $build) @('System.dll', 'System.Core.dll')
    & obj\tests.exe (Resolve-Path obj\SnwlConnect.exe).Path
    if ($LASTEXITCODE -ne 0) { throw "tests failed ($LASTEXITCODE)" }
}
