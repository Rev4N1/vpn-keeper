# build.ps1 - builds dist\vpn-keeper.exe with the C# compiler that ships
# with Windows (.NET Framework 4.8). No SDK or NuGet needed; CI runs the same.
#
#   .\build.ps1            build
#   .\build.ps1 -Test      build, then run the self-test against the fake client
param(
    [switch]$Test,
    [string]$Version
)
$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { throw "C# compiler not found at $csc (.NET Framework 4.8 is required)" }

# Version: the -Version argument, else git describe on v* tags (v1.2.3, v1.2.3-4-gabc1234, or a hash).
if (-not $Version) {
    # Windows PowerShell turns git's stderr into an error under 'Stop'.
    $ErrorActionPreference = 'Continue'
    $Version = (& git describe --tags --match "v*" --always --dirty 2>$null)
    $ErrorActionPreference = 'Stop'
    if (-not $Version) { $Version = 'dev' }
}
$numeric = '0.0.0.0'
if ($Version -match '^v?(\d+)\.(\d+)\.(\d+)') { $numeric = "$($Matches[1]).$($Matches[2]).$($Matches[3]).0" }

New-Item -ItemType Directory -Force obj, dist, obj\test | Out-Null
@"
// Generated by build.ps1 - do not edit.
using System.Reflection;
[assembly: AssemblyTitle("vpn-keeper")]
[assembly: AssemblyProduct("vpn-keeper")]
[assembly: AssemblyVersion("$numeric")]
[assembly: AssemblyFileVersion("$numeric")]
[assembly: AssemblyInformationalVersion("$Version")]
namespace VpnKeeper { static class BuildInfo { public const string Version = "$Version"; } }
"@ | Set-Content -Encoding UTF8 obj\BuildInfo.cs

function Compile([string]$out, [string]$target, [string[]]$sources, [string[]]$refs) {
    $cscArgs = @('/nologo', "/target:$target", '/optimize+', '/warnaserror+', '/nowarn:0649', '/platform:anycpu',
              '/codepage:65001', "/out:$out") + ($refs | ForEach-Object { "/r:$_" }) + $sources
    & $csc @cscArgs
    if ($LASTEXITCODE -ne 0) { throw "compile failed: $out" }
}

$src = @(Get-ChildItem src\*.cs | ForEach-Object FullName) + (Resolve-Path obj\BuildInfo.cs).Path
Compile 'dist\vpn-keeper.exe' 'exe' $src @('System.dll', 'System.Core.dll')
Copy-Item vpn-keeper.conf.example dist\ -Force
Copy-Item README.md dist\ -Force
Write-Host "built dist\vpn-keeper.exe ($Version)"

if ($Test) {
    # The fake client must be called SnwlConnect.exe: the agent looks for that process name.
    Compile 'obj\test\SnwlConnect.exe' 'winexe' @((Resolve-Path tests\FakeSnwlConnect.cs).Path, (Resolve-Path src\Totp.cs).Path) `
        @('System.dll', 'System.Drawing.dll', 'System.Windows.Forms.dll')
    & .\dist\vpn-keeper.exe selftest (Resolve-Path obj\test\SnwlConnect.exe).Path
    if ($LASTEXITCODE -ne 0) { throw "self-test failed ($LASTEXITCODE)" }
}
